#!/usr/bin/env python3
"""Write site/forever-icons.txt: the icons WoW Forever's own spells and items use.

Reads three of the client's database tables for a WoW Forever build, as exported by
wago.tools (Blizzard's DB2 data, one CSV per table):
    SpellMisc              spell -> icon file ID
    Item / ItemAppearance  item -> icon file ID
    ManifestInterfaceData  icon file ID -> file name
Only the resulting list of icon names is saved.

Usage:
    python3 tools/build_forever_icons.py [build]     # default: 1.60.1.70094
Then rebuild the browser index: python3 tools/build_icons.py
"""
import csv
import io
import pathlib
import sys
import urllib.request

SITE = pathlib.Path(__file__).resolve().parent.parent
OUT = SITE / "forever-icons.txt"
DEFAULT_BUILD = "1.60.1.70094"


def table(name, build):
    url = f"https://wago.tools/db2/{name}/csv?build={build}"
    data = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"}),
                                  timeout=300).read().decode("utf-8")
    return csv.DictReader(io.StringIO(data))


def file_ids(rows, columns):
    ids = set()
    for row in rows:
        for column in columns:
            value = int(float(row.get(column) or 0))
            if value:
                ids.add(value)
    return ids


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_BUILD
    csv.field_size_limit(10**9)
    names = {int(r["ID"]): r["FileName"].rsplit(".", 1)[0].lower()
             for r in table("ManifestInterfaceData", build)
             if r["FilePath"].lower().replace("\\", "/").startswith("interface/icons")}
    used = file_ids(table("SpellMisc", build), ["SpellIconFileDataID", "ActiveIconFileDataID"])
    used |= file_ids(table("Item", build), ["IconFileDataID"])
    used |= file_ids(table("ItemAppearance", build), ["DefaultIconFileDataID"])
    icons = sorted({names[f] for f in used if f in names})
    OUT.write_text(f"# Icons used by WoW Forever's spells and items (build {build}).\n"
                   "# Generated by tools/build_forever_icons.py.\n" + "\n".join(icons) + "\n", encoding="utf-8")
    print(f"{len(icons)} icons -> {OUT}")


if __name__ == "__main__":
    main()
